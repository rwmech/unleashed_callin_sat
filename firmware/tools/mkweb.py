# Purpose:      Gzips every page in firmware/web/, and the xterm.js assets
#               fetch_web.py cached, into one generated C++ source file in
#               firmware/src/webassets/ (ignored by git), with the header
#               that names them.
#
#               Why precompressed rather than compressed per request: there
#               is no built-in support in esp_http_server and there will not
#               be (IDF issue 18816 asked for it and was closed "Won't Do"),
#               and gzipping 290 KB on an ESP32 per page view would be
#               absurd. Brotli is not an option at all: browsers advertise
#               `br` only over HTTPS, and a captive portal cannot be HTTPS.
#
#               Why byte arrays rather than CMake's EMBED_FILES, which is
#               the tidier mechanism: EMBED_FILES generates .S files through
#               a cmake custom command, and PlatformIO drives the IDF
#               through its own SCons, which does not know how to produce
#               them ("Source `xterm_js.gz.S' not found"). An array is about
#               330 KB of source text nobody reads, which is the price of a
#               build that works. Worth re-trying if this ever moves to
#               idf.py.
